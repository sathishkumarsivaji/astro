/**
 * Test: Isolated Fixture-Based Node Modules Dependency Regression
 * ================================================================
 * Refactored to test dependency completeness strictly using isolated
 * temporary fixtures in os.tmpdir(). Does NOT require or assume the real
 * project's node_modules exists, making it 100% compatible with clean
 * release archives and zero-dependency environments.
 *
 * Test cases:
 * 1. Complete mock installation (passes)
 * 2. Missing required package (fails)
 * 3. Missing required binary (fails)
 * 4. Incomplete package installation (fails)
 * 5. Missing node_modules directory (fails)
 * 6. Interrupted installation (fails)
 */

import { strict as assert } from "node:assert";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

console.log("\n============================================================");
console.log(" TEST: ISOLATED NODE_MODULES CERTIFICATION REGRESSION SUITE");
console.log("============================================================\n");

const REQUIRED_PACKAGES = [
  "astronomy-engine",
  "react",
  "react-dom",
  "lucide-react",
  "jspdf",
  "dompurify",
  "vite",
  "oxlint"
];

// Function representing the Gate 12 verification logic
function verifyNodeModulesCompleteness(nodeModulesDir) {
  const nodeModulesExists = fs.existsSync(nodeModulesDir);
  if (!nodeModulesExists) {
    return { success: false, reason: "node_modules missing" };
  }

  let missingPackages = [];
  let missingBinaries = [];

  for (const pkgName of REQUIRED_PACKAGES) {
    const pkgPath = path.join(nodeModulesDir, pkgName, "package.json");
    if (!fs.existsSync(pkgPath)) {
      missingPackages.push(pkgName);
    }
  }

  const binDir = path.join(nodeModulesDir, ".bin");
  const requiredBins = process.platform === "win32"
    ? ["vite.cmd", "oxlint.cmd"]
    : ["vite", "oxlint"];

  for (const binName of requiredBins) {
    const binPath = path.join(binDir, binName);
    if (!fs.existsSync(binPath)) {
      missingBinaries.push(binName);
    }
  }

  if (missingPackages.length > 0 || missingBinaries.length > 0) {
    return {
      success: false,
      reason: `Incomplete node_modules. Missing packages: [${missingPackages.join(", ")}]; missing binaries: [${missingBinaries.join(", ")}]`
    };
  }

  return { success: true };
}

// Helper to construct a complete mock installation in an isolated directory
function setupMockInstallation(targetDir, options = {}) {
  fs.mkdirSync(targetDir, { recursive: true });

  const binDir = path.join(targetDir, ".bin");
  fs.mkdirSync(binDir, { recursive: true });

  const bins = process.platform === "win32" ? ["vite.cmd", "oxlint.cmd"] : ["vite", "oxlint"];
  for (const bin of bins) {
    if (!options.omitBinaries?.includes(bin)) {
      fs.writeFileSync(path.join(binDir, bin), "#!/bin/sh\necho ok\n");
    }
  }

  for (const pkg of REQUIRED_PACKAGES) {
    if (options.omitPackages?.includes(pkg)) continue;

    const pkgDir = path.join(targetDir, pkg);
    fs.mkdirSync(pkgDir, { recursive: true });

    if (!options.corruptPackages?.includes(pkg)) {
      fs.writeFileSync(path.join(pkgDir, "package.json"), JSON.stringify({ name: pkg, version: "1.0.0" }));
    }
  }

  if (options.interrupted) {
    fs.mkdirSync(path.join(targetDir, ".staging"), { recursive: true });
  }
}

// Create isolated temporary directory sandbox
const sandbox = fs.mkdtempSync(path.join(os.tmpdir(), "astroverse-gate12-"));
let passed = 0;
let failed = 0;

function checkCase(name, fn) {
  try {
    fn();
    console.log(`  ✓ [PASS] ${name}`);
    passed++;
  } catch (err) {
    console.error(`  ✗ [FAIL] ${name}: ${err.message}`);
    failed++;
  }
}

try {
  // Case 1: Complete mock installation
  checkCase("Case 1: Complete mock installation passes verification", () => {
    const dir = path.join(sandbox, "case1_complete", "node_modules");
    setupMockInstallation(dir);
    const res = verifyNodeModulesCompleteness(dir);
    assert.strictEqual(res.success, true, "Complete mock installation must pass");
  });

  // Case 2: Missing required package
  checkCase("Case 2: Missing required package correctly fails verification", () => {
    const dir = path.join(sandbox, "case2_missing_pkg", "node_modules");
    setupMockInstallation(dir, { omitPackages: ["lucide-react"] });
    const res = verifyNodeModulesCompleteness(dir);
    assert.strictEqual(res.success, false);
    assert(res.reason.includes("lucide-react"), "Failure reason must identify missing package");
  });

  // Case 3: Missing required binary
  checkCase("Case 3: Missing required binary correctly fails verification", () => {
    const dir = path.join(sandbox, "case3_missing_bin", "node_modules");
    const binToOmit = process.platform === "win32" ? "oxlint.cmd" : "oxlint";
    setupMockInstallation(dir, { omitBinaries: [binToOmit] });
    const res = verifyNodeModulesCompleteness(dir);
    assert.strictEqual(res.success, false);
    assert(res.reason.includes(binToOmit), "Failure reason must identify missing binary");
  });

  // Case 4: Incomplete package installation (dir exists but package.json missing)
  checkCase("Case 4: Incomplete package installation correctly fails verification", () => {
    const dir = path.join(sandbox, "case4_incomplete_pkg", "node_modules");
    setupMockInstallation(dir, { corruptPackages: ["jspdf"] });
    const res = verifyNodeModulesCompleteness(dir);
    assert.strictEqual(res.success, false);
    assert(res.reason.includes("jspdf"), "Failure reason must identify incomplete package");
  });

  // Case 5: Missing node_modules directory
  checkCase("Case 5: Missing node_modules directory correctly fails verification", () => {
    const dir = path.join(sandbox, "case5_missing_dir", "node_modules");
    // Do not create directory
    const res = verifyNodeModulesCompleteness(dir);
    assert.strictEqual(res.success, false);
    assert.strictEqual(res.reason, "node_modules missing");
  });

  // Case 6: Interrupted installation with partial packages and staging artifact
  checkCase("Case 6: Interrupted installation correctly fails verification", () => {
    const dir = path.join(sandbox, "case6_interrupted", "node_modules");
    setupMockInstallation(dir, {
      omitPackages: ["vite", "oxlint", "dompurify"],
      interrupted: true
    });
    const res = verifyNodeModulesCompleteness(dir);
    assert.strictEqual(res.success, false);
    assert(res.reason.includes("vite"));
  });

} finally {
  // Clean up isolated sandbox
  try {
    fs.rmSync(sandbox, { recursive: true, force: true });
  } catch {}
}

console.log("\n============================================================");
console.log(` SUMMARY: ${passed} passed, ${failed} failed.`);
console.log("============================================================\n");

process.exit(failed > 0 ? 1 : 0);
