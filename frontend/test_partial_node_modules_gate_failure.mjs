/**
 * Test: Deliberately Leave Partial node_modules to Verify Gate 12 Fails
 * =====================================================================
 * Proves that Gate 12 does not treat mere directory existence as proof
 * of installation. A missing essential package or binary in node_modules
 * must cause Gate 12 verification to fail.
 */

import { strict as assert } from "node:assert";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");
const FRONTEND_DIR = path.join(ROOT, "frontend");
const NODE_MODULES = path.join(FRONTEND_DIR, "node_modules");

console.log("\n============================================================");
console.log(" TEST: PARTIAL NODE_MODULES CERTIFICATION FAILURE REGRESSION");
console.log("============================================================\n");

// Function representing the Gate 12 verification logic
function verifyNodeModulesCompleteness(nodeModulesDir) {
  const nodeModulesExists = fs.existsSync(nodeModulesDir);
  if (!nodeModulesExists) {
    return { success: false, reason: "node_modules missing" };
  }

  const requiredPackages = [
    "astronomy-engine",
    "react",
    "react-dom",
    "lucide-react",
    "jspdf",
    "dompurify",
    "vite",
    "oxlint"
  ];

  let missingPackages = [];
  let missingBinaries = [];

  for (const pkgName of requiredPackages) {
    const pkgPath = path.join(nodeModulesDir, pkgName, "package.json");
    if (!fs.existsSync(pkgPath)) {
      missingPackages.push(pkgName);
    }
  }

  const binDir = path.join(nodeModulesDir, ".bin");
  const requiredBins = process.platform === "win32"
    ? ["vite.cmd", "oxlint.cmd"]
    : ["vite", "oxlint"];

  for (const binName of requiredBins) {
    const binPath = path.join(binDir, binName);
    if (!fs.existsSync(binPath)) {
      missingBinaries.push(binName);
    }
  }

  if (missingPackages.length > 0 || missingBinaries.length > 0) {
    return {
      success: false,
      reason: `Incomplete node_modules. Missing packages: [${missingPackages.join(", ")}]; missing binaries: [${missingBinaries.join(", ")}]`
    };
  }

  return { success: true };
}

// 1. Verify that real node_modules passes
const realCheck = verifyNodeModulesCompleteness(NODE_MODULES);
assert.equal(realCheck.success, true, "Existing complete node_modules must pass");
console.log("✓ Complete node_modules passes verification");

// 2. Simulate partial node_modules in a temporary sandbox
const mockDir = path.join(FRONTEND_DIR, "mock_partial_node_modules");
try {
  fs.mkdirSync(mockDir, { recursive: true });
  // Add only react and astronomy-engine, leaving out vite, oxlint, lucide-react, binaries
  fs.mkdirSync(path.join(mockDir, "react"), { recursive: true });
  fs.writeFileSync(path.join(mockDir, "react/package.json"), "{}");
  fs.mkdirSync(path.join(mockDir, "astronomy-engine"), { recursive: true });
  fs.writeFileSync(path.join(mockDir, "astronomy-engine/package.json"), "{}");

  const partialCheck = verifyNodeModulesCompleteness(mockDir);
  assert.equal(partialCheck.success, false, "Partial node_modules MUST FAIL Gate 12 check");
  assert(partialCheck.reason.includes("Missing packages"), "Failure reason must list missing packages");
  assert(partialCheck.reason.includes("missing binaries"), "Failure reason must list missing binaries");
  console.log(`✓ Partial node_modules correctly fails Gate 12: ${partialCheck.reason}`);
} finally {
  if (fs.existsSync(mockDir)) {
    fs.rmSync(mockDir, { recursive: true, force: true });
  }
}

console.log("\n============================================================");
console.log(" PARTIAL NODE_MODULES REGRESSION TEST PASSED (100%)");
console.log("============================================================\n");
