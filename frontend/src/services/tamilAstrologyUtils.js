/**
 * Strips any English transliteration parenthetical from bilingual strings:
 * e.g. "வைரம் (Diamond)" -> "வைரம்", "மேஷம் (Aries)" -> "மேஷம்"
 */
export function cleanEnglishParentheses(text) {
  if (typeof text !== "string") return text;
  return text
    .replace(/\s*\([A-Za-z0-9\s,&'\-\/]+\)/g, "")
    .replace(/\s*–\s*[A-Za-z0-9\s,&'\-\/]+$/g, "")
    .trim();
}

/**
 * Formats degrees nicely in Tamil
 */
export function formatTamilDegree(deg) {
  if (typeof deg !== "number" || isNaN(deg)) return "";
  return ` ${deg.toFixed(2)}° பாகையில்`;
}
